import struct NIOCore.ByteBuffer
import struct NIOCore.NIOAsyncChannelOutboundWriter
import Logging
import NeedleTailLogger
import NeedleTailAsyncSequence

/// A protocol that defines methods for transporting messages in an IRC context.
/// Conforming types must be classes and are required to be `Sendable` for safe concurrency.
public protocol NeedleTailWriterDelegate: AnyObject, Sendable {
    
    /// Size limits `sendAndFlushMessage` checks before writing a text line. `nil`, the default,
    /// checks none, which NeedleTail's larger lines need. Return ``IRCLineLimits/standardClient``
    /// or ``IRCLineLimits/standardServer`` on a connection to a standard IRC network.
    var outboundLineLimits: IRCLineLimits? { get }
    
    /// Transports a stream of messages generated by the provided message generator.
    ///
    /// - Parameters:
    ///   - messageGenerator: An instance of `IRCMessageGenerator` that generates messages to be sent.
    ///   - executor: An optional executor of type `AnyExecutor` for managing task execution.
    ///   - logger: An instance of `NeedleTailLogger` for logging purposes. Defaults to a logger with a specific label.
    ///   - writer: An instance of `NIOAsyncChannelOutboundWriter<IRCMessage>` used to write the messages.
    ///   - origin: A `String` representing the origin of the messages. Defaults to an empty string.
    ///   - target: The recipient's nick for numeric and CAP replies (RFC 2812 §2.4). Defaults to `nil`.
    ///   - command: An instance of `IRCCommand` representing the command associated with the messages.
    ///   - tags: An optional array of `IRCTag` representing any tags associated with the messages.
    ///   - authPacket: An optional `AuthPacket` for authentication information.
    /// - Throws: An error if message transport fails.
    func transportMessage(
        _ messageGenerator: IRCMessageGenerator,
        executor: any AnyExecutor,
        logger: NeedleTailLogger,
        writer: NIOAsyncChannelOutboundWriter<IRCFrame>,
        origin: String,
        target: String?,
        command: IRCCommand,
        tags: [IRCTag]?,
        authPacket: NeedleTailIRC.AuthPacket?
    ) async throws
    
    /// Sends and flushes a message using the provided parameters.
    ///
    /// - Parameters:
    ///   - executor: An optional executor of type `AnyExecutor` for managing task execution.
    ///   - logger: An instance of `NeedleTailLogger` for logging purposes.
    ///   - writer: An instance of `NIOAsyncChannelOutboundWriter<IRCMessage>` used to write the message.
    ///   - message: An instance of `IRCMessage` representing the message to be sent.
    /// - Throws: An error if sending or flushing the message fails.
    func sendAndFlushMessage<OutboundOut>(
        executor: (any AnyExecutor)?,
        logger: NeedleTailLogger,
        writer: NIOAsyncChannelOutboundWriter<OutboundOut>,
        message: OutboundOut
    ) async throws
}

extension NeedleTailWriterDelegate {
    
    public var outboundLineLimits: IRCLineLimits? { nil }
    
    /// Transports a stream of messages generated by the provided message generator.
    ///
    /// - Parameters:
    ///   - messageGenerator: An instance of `IRCMessageGenerator` that generates messages to be sent.
    ///   - executor: An optional executor of type `AnyExecutor` for managing task execution.
    ///   - logger: An instance of `NeedleTailLogger` for logging purposes. Defaults to a logger with a specific label.
    ///   - writer: An instance of `NIOAsyncChannelOutboundWriter<IRCFrame>` used to write the messages.
    ///   - origin: A `String` representing the origin of the messages. Defaults to an empty string.
    ///   - target: The recipient's nick for numeric and CAP replies (RFC 2812 §2.4). Defaults to `nil`.
    ///   - command: An instance of `IRCCommand` representing the command associated with the messages.
    ///   - tags: An optional array of `IRCTag` representing any tags associated with the messages.
    ///   - authPacket: An optional `AuthPacket` for authentication information.
    /// - Throws: An error if message transport fails.
    public func transportMessage(
        _ messageGenerator: IRCMessageGenerator,
        executor: any AnyExecutor,
        logger: NeedleTailLogger = NeedleTailLogger("[ com.needletails.writer.delegate ]"),
        writer: NIOAsyncChannelOutboundWriter<IRCFrame>,
        origin: String = "",
        target: String? = nil,
        command: IRCCommand,
        tags: [IRCTag]? = nil,
        authPacket: NeedleTailIRC.AuthPacket? = nil
    ) async throws {
        let messageStream = await messageGenerator.createMessages(
            origin: origin,
            target: target,
            command: command,
            tags: tags,
            authPacket: authPacket,
            logger: logger
        )
        try await transportMessage(
            messages: messageStream,
            executor: executor,
            logger: logger,
            writer: writer
        )
    }

    /// Transports a pre-built throwing stream of IRC frames.
    ///
    /// Throws ``IRCMessageGeneratorError/zeroFramesGenerated`` when the stream
    /// finishes without yielding any frames — a silent-send failure mode that
    /// previously looked like a successful local write.
    public func transportMessage(
        messages: AsyncThrowingStream<IRCMessage, Error>,
        executor: any AnyExecutor,
        logger: NeedleTailLogger = NeedleTailLogger("[ com.needletails.writer.delegate ]"),
        writer: NIOAsyncChannelOutboundWriter<IRCFrame>
    ) async throws {
        var writtenFrames = 0
        for try await message in messages {
            try await self.sendAndFlushMessage(
                executor: executor,
                logger: logger,
                writer: writer,
                message: .text(message))
            writtenFrames += 1
        }
        guard writtenFrames > 0 else {
            throw IRCMessageGeneratorError.zeroFramesGenerated
        }
    }
    
    /// Sends and flushes a message using the provided parameters.
    ///
    /// This method handles both cases where an executor is provided and where it is not.
    ///
    /// - Parameters:
    ///   - executor: An optional executor of type `AnyExecutor` for managing task execution. If `nil`, the task will run without a specific executor.
    ///   - logger: An instance of `NeedleTailLogger` for logging purposes. Defaults to a logger with a specific label.
    ///   - writer: An instance of `NIOAsyncChannelOutboundWriter<IRCMessage>` used to write the message.
    ///   - message: An instance of `IRCMessage` representing the message to be sent.
    /// - Throws: An error if sending or flushing the message fails, or the
    ///   ``IRCMessageGeneratorError`` from ``IRCMessage/validateWireLine(limits:)`` before anything is
    ///   written when a text line is invalid.
    public func sendAndFlushMessage<OutboundOut>(
        executor: (any AnyExecutor)? = nil,
        logger: NeedleTailLogger = NeedleTailLogger("[ com.needletails.writer.delegate ]"),
        writer: NIOAsyncChannelOutboundWriter<OutboundOut>,
        message: OutboundOut
    ) async throws {
        // Reject an invalid line here: a throw inside the NIO encoder fails every later write.
        switch message {
        case let frame as IRCFrame:
            if case .text(let line) = frame { try line.validateWireLine(limits: outboundLineLimits) }
        case let line as IRCMessage:
            try line.validateWireLine(limits: outboundLineLimits)
        default:
            break
        }
        try await withThrowingDiscardingTaskGroup { group in
            if let executor {
                group.addTask(executorPreference: executor) {
                    try await self.writeMessage(
                        writer: writer,
                        message: message,
                        logger: logger
                    )
                }
            } else {
                group.addTask {
                    try await self.writeMessage(
                        writer: writer,
                        message: message,
                        logger: logger
                    )
                }
            }
        }
    }
    
    
    /// Writes a message to the provided writer.
    ///
    /// This method encodes the message and handles any errors that occur during the writing process.
    ///
    /// - Parameters:
    ///   - writer: An instance of `NIOAsyncChannelOutboundWriter<IRCMessage>` used to write the message.
    ///   - message: An instance of `IRCMessage` representing the message to be sent.
    ///   - logger: An instance of `NeedleTailLogger` for logging purposes.
    /// - Throws: An error if writing the message fails.
    private func writeMessage<OutboundOut>(
        writer: NIOAsyncChannelOutboundWriter<OutboundOut>,
        message: OutboundOut,
        logger: NeedleTailLogger
    ) async throws {
        do {
            try await writer.write(message)
        } catch {
            // During intentional transport rotation (for example after device-link sync),
            // late writes can race with `finish()` and surface as already-finished.
            // Keep that as trace-level noise while preserving true send failures as errors.
            if isAlreadyFinishedWriteError(error) {
                logger.log(level: .trace, message: "Send And Flush skipped on finished writer: \(error)")
            } else {
                logger.log(level: .error, message: "Send And Flush Error: \(error)")
            }
            throw error
        }
    }

    private func isAlreadyFinishedWriteError(_ error: Error) -> Bool {
        String(describing: error).contains("NIOAsyncWriterError.alreadyFinished")
    }
}
